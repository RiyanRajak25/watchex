-- 1. Enable Required Extensions
create extension if not exists "uuid-ossp";
create extension if not exists "pgcrypto";

-- 2. Drop existing triggers if re-running
drop trigger if exists set_updated_at on public.histories;
drop trigger if exists set_comments_updated_at on public.comments;
drop trigger if exists set_ratings_updated_at on public.ratings;
drop trigger if exists set_movie_cache_updated_at on public.movie_cache;
drop trigger if exists set_generated_articles_updated_at on public.generated_articles;
drop trigger if exists on_auth_user_created on auth.users;

-- 3. Trigger Function for updated_at
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ==============================================================================
-- Table: Profiles (User Identity & Metadata)
-- ==============================================================================
create table if not exists public.profiles (
  id uuid not null references auth.users(id) on delete cascade primary key,
  username text unique,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Trigger to automatically create a profile entry when a new auth user signs up
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, username, avatar_url)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'user_name', new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
    new.raw_user_meta_data->>'avatar_url'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create or replace trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ==============================================================================
-- Table: Histories (Stream Tracking & Resume Positions)
-- ==============================================================================
create table if not exists public.histories (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  media_id integer not null,
  type text not null check (type in ('movie', 'tv')),
  season integer not null default 0,
  episode integer not null default 0,
  duration double precision not null default 0,
  last_position double precision not null default 0,
  completed boolean not null default false,
  adult boolean not null default false,
  backdrop_path text,
  poster_path text,
  release_date date,
  title text not null,
  vote_average numeric(4,1) not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, media_id, type, season, episode)
);

create trigger set_updated_at before update on public.histories
  for each row execute function public.set_updated_at();

-- ==============================================================================
-- Table: Watchlists (Custom User Lists: watching, planning, completed, etc.)
-- ==============================================================================
create table if not exists public.watchlists (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  media_id integer not null,
  type text not null check (type in ('movie', 'tv')),
  status text not null check (status in ('watching', 'planning', 'completed', 'on_hold', 'dropped')),
  title text not null,
  poster_path text,
  rating numeric(4,1) default 0,
  created_at timestamptz not null default now(),
  unique (user_id, media_id, type)
);

-- ==============================================================================
-- Table: Comments (Threaded Discussions & Flags)
-- ==============================================================================
create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  media_id integer not null,
  media_type text not null check (media_type in ('movie', 'tv')),
  parent_id bigint references public.comments(id) on delete cascade,
  content text not null,
  flagged boolean not null default false,
  flag_reason text,
  flagged_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create trigger set_comments_updated_at before update on public.comments
  for each row execute function public.set_updated_at();

-- ==============================================================================
-- Table: Comment Likes
-- ==============================================================================
create table if not exists public.comment_likes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  comment_id bigint not null references public.comments(id) on delete cascade,
