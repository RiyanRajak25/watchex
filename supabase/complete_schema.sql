create trigger set_movie_cache_updated_at before update on public.movie_cache
  for each row execute function public.set_updated_at();

-- ==============================================================================
-- Table: Generated Articles (AI Long-Tail Explanations & Guides)
-- ==============================================================================
create table if not exists public.generated_articles (
  id uuid primary key default gen_random_uuid(),
  movie_id integer not null,
  media_type text not null default 'movie' check (media_type in ('movie', 'tv')),
  article_slug text not null,
  title text not null,
  content text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (movie_id, media_type) references public.movie_cache(id, media_type) on delete cascade,
  constraint unique_movie_slug unique (movie_id, media_type, article_slug)
);

create trigger set_generated_articles_updated_at before update on public.generated_articles
  for each row execute function public.set_updated_at();

-- ==============================================================================
-- Table: Long Tail Queries
-- ==============================================================================
