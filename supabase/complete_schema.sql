-- ==============================================================================
-- Table: Ratings (1-10 User Media Ratings)
-- ==============================================================================
create table if not exists public.ratings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  media_id integer not null,
  media_type text not null check (media_type in ('movie', 'tv')),
  score integer not null check (score >= 1 and score <= 10),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, media_id, media_type)
);

create trigger set_ratings_updated_at before update on public.ratings
  for each row execute function public.set_updated_at();

-- ==============================================================================
-- Table: Movie Cache (TMDB Metadata & Video Trailer Keys)
-- ==============================================================================
create table if not exists public.movie_cache (
  id integer not null, -- TMDB ID
