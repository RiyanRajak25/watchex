  id uuid primary key default gen_random_uuid(),
  query text not null unique,
  volume integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ==============================================================================
-- Table: Indexing Tracking (Google Indexing API Rate Limit Protection)
-- ==============================================================================
create table if not exists public.indexing_tracking (
  id serial primary key,
  date date not null unique,
  push_count integer not null default 0,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

-- RPC for incrementing daily indexing count
create or replace function public.increment_indexing_count(row_date date)
returns void language plpgsql security definer as $$
begin
  insert into public.indexing_tracking (date, push_count)
  values (row_date, 1)
  on conflict (date)
  do update set push_count = indexing_tracking.push_count + 1, updated_at = now();
end;
$$;

