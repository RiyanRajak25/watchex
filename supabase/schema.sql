-- WatchEX.tech Complete Database Schema

-- Users Profile (Depends on auth.users)
create table public.profiles (
  id uuid not null references auth.users(id) on delete cascade primary key,
  username text unique,
  avatar_url text,
  created_at timestamp with time zone not null default now()
);

-- Histories
create table public.histories (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  media_id integer not null,
  type text not null check (type in ('movie','tv')),
  season integer not null default 0,
  episode integer not null default 0,
  duration double precision not null default 0,
  last_position double precision not null default 0,
  completed boolean not null default false,
  adult boolean not null default false,
  backdrop_path text,
  poster_path text,
  release_date date,
  title text not null,
  vote_average numeric(4,1) not null default 0,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  unique (user_id, media_id, type, season, episode)
);

-- Watchlists (5 tabs)
create table public.watchlists (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  media_id integer not null,
  type text not null check (type in ('movie','tv')),
  status text not null check (status in ('watching', 'planning', 'completed', 'on_hold', 'dropped')),
  title text not null,
  poster_path text,
  rating numeric(4,1) default 0,
  created_at timestamp with time zone not null default now(),
  unique (user_id, media_id, type)
);

-- Comments
create table public.comments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  media_id integer not null,
  media_type text not null check (media_type in ('movie','tv')),
  parent_id bigint references public.comments(id) on delete cascade,
  content text not null,
  flagged boolean not null default false,
  flag_reason text,
  flagged_at timestamp with time zone,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);

-- Comment Likes
create table public.comment_likes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  comment_id bigint not null references public.comments(id) on delete cascade,
  created_at timestamp with time zone not null default now(),
  unique (user_id, comment_id)
);

-- Triggers for updated_at
create or replace function public.set_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end; $$;

create trigger set_updated_at before update on public.histories for each row execute function public.set_updated_at();
create trigger set_comments_updated_at before update on public.comments for each row execute function public.set_updated_at();

-- RLS Policies
alter table public.profiles enable row level security;
alter table public.histories enable row level security;
alter table public.watchlists enable row level security;
alter table public.comments enable row level security;
alter table public.comment_likes enable row level security;

create policy "Users can view all profiles" on public.profiles for select using (true);
create policy "Users update own profile" on public.profiles for update using (auth.uid() = id);

create policy "Users view own histories" on public.histories for select to authenticated using (auth.uid() = user_id);
create policy "Users insert own histories" on public.histories for insert to authenticated with check (auth.uid() = user_id);
create policy "Users update own histories" on public.histories for update to authenticated using (auth.uid() = user_id);
create policy "Users delete own histories" on public.histories for delete to authenticated using (auth.uid() = user_id);

create policy "Users view own watchlists" on public.watchlists for select to authenticated using (auth.uid() = user_id);
create policy "Users insert own watchlists" on public.watchlists for insert to authenticated with check (auth.uid() = user_id);
create policy "Users update own watchlists" on public.watchlists for update to authenticated using (auth.uid() = user_id);
create policy "Users delete own watchlists" on public.watchlists for delete to authenticated using (auth.uid() = user_id);

create policy "Anyone can read comments" on public.comments for select using (true);
create policy "Auth users create comments" on public.comments for insert to authenticated with check (auth.uid() = user_id);
create policy "Users update own comments" on public.comments for update to authenticated using (auth.uid() = user_id);
create policy "Users delete own comments" on public.comments for delete to authenticated using (auth.uid() = user_id);

create policy "Anyone can read likes" on public.comment_likes for select using (true);
create policy "Auth users add likes" on public.comment_likes for insert to authenticated with check (auth.uid() = user_id);
create policy "Users remove own likes" on public.comment_likes for delete to authenticated using (auth.uid() = user_id);
